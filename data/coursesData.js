export function getAllCourses() {
  const list = [...ALL_COURSES];
  for (let i = 11; i <= 30; i++) {
    const generated = getCourseById(i);
    if (generated) list.push(generated);
  }
  return list;
}

export function getRelatedCourses(currentCourse, count = 3) {
  const all = getAllCourses();
  const sameCategory = all.filter((c) => c.id !== currentCourse.id && c.category === currentCourse.category);
  if (sameCategory.length >= count) {
    return sameCategory.slice(0, count);
  }
  const other = all.filter((c) => c.id !== currentCourse.id && c.category !== currentCourse.category);
  return [...sameCategory, ...other].slice(0, count);
}
